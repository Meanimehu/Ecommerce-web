/**
 * npm run gen:error-codes -- --from ../Ecommerce/docs/api/api-contract.md
 *
 * Reads the backend's error catalogue (api-contract.md, section 11) and writes two files that are
 * never edited by hand, in src/types/generated/:
 *   backend-error-codes.json  the codes and their HTTP status, used by the message check
 *   backend-error-codes.ts    the BackendErrorCode enum the code compares with (Document 7, 20.4)
 * Run it again whenever the backend catalogue changes.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

interface CatalogueEntry {
  code: string;
  status: number;
}

const generatedFolder = new URL('../src/types/generated/', import.meta.url);
const jsonFile = fileURLToPath(new URL('backend-error-codes.json', generatedFolder));
const enumFile = fileURLToPath(new URL('backend-error-codes.ts', generatedFolder));

function readContractPath(): string {
  const flagPosition = process.argv.indexOf('--from');
  const contractPath = flagPosition >= 0 ? process.argv[flagPosition + 1] : undefined;
  if (!contractPath) {
    console.error(
      'Say where the backend contract is: npm run gen:error-codes -- --from <path>/docs/api/api-contract.md',
    );
    process.exit(1);
  }
  return contractPath;
}

function readCatalogue(contractText: string): CatalogueEntry[] {
  const sectionStart = contractText.indexOf('## 11. Error catalogue');
  const sectionEnd = contractText.indexOf('\n## 12.', sectionStart);
  if (sectionStart < 0 || sectionEnd < 0) {
    throw new Error('Section 11 (Error catalogue) not found');
  }

  const catalogueSection = contractText.slice(sectionStart, sectionEnd);
  const tableRows = catalogueSection.matchAll(/^\| `([A-Z][A-Z0-9_]+)` \| (\d{3}) \|/gm);

  return [...tableRows].map((row) => ({ code: row[1] ?? '', status: Number(row[2]) }));
}

/** OTP_RESEND_WAIT becomes OtpResendWait. */
export function enumMemberName(code: string): string {
  return code
    .toLowerCase()
    .split('_')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join('');
}

export function enumSource(catalogue: readonly CatalogueEntry[]): string {
  const members = catalogue.map((entry) => `  ${enumMemberName(entry.code)} = '${entry.code}',`);
  return [
    '/**',
    ' * GENERATED by npm run gen:error-codes from the backend error catalogue (api-contract.md, section 11).',
    ' * Do not edit by hand. The values are the backend codes exactly (Document 7, section 20.4).',
    ' */',
    'export enum BackendErrorCode {',
    ...members,
    '}',
    '',
  ].join('\n');
}

async function main(): Promise<void> {
  const contractText = await readFile(readContractPath(), 'utf8');
  const catalogue = readCatalogue(contractText);

  const storedCatalogue = { source: 'docs/api/api-contract.md, section 11', codes: catalogue };
  await writeFile(jsonFile, `${JSON.stringify(storedCatalogue, null, 2)}\n`);
  await writeFile(enumFile, enumSource(catalogue));

  console.log(`Stored ${catalogue.length} backend error codes and the BackendErrorCode enum.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await main();
}
