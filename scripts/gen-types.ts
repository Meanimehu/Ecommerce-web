/**
 * Request types from the backend's OpenAPI description (Document 7, D7-02; Document 3, D3-01).
 *
 *   npm run gen:types          fetch the description from BACKEND_URL, store it, and regenerate the types
 *   npm run check:types        regenerate the types from the stored description; fail if they differ (runs in CI)
 *   npm run check:types:live   fetch the description again; fail if it differs from the stored copy (a backend change)
 *
 * It also writes the list of backend calls by their listed names (`GET /admin/vendors/{id}`), the only call names a server log
 * may hold (Document 7, section 20.10).
 *
 * The description is switched off in production, so it comes from a development or staging backend (D7-02; check T7-3).
 * It has request fields but no response shapes (backend gap B4); responses are checked by Zod schemas instead.
 * The generated files are never edited by hand.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = fileURLToPath(new URL('..', import.meta.url));
const SPEC = `${root}src/types/generated/backend-openapi.json`;
const TYPES = `${root}src/types/generated/backend-api.d.ts`;
const CALLS = `${root}src/types/generated/backend-calls.ts`;
const HEADER = `/**\n * GENERATED by npm run gen:types from the backend's OpenAPI description (src/types/generated/backend-openapi.json).\n * Do not edit by hand. Request types only: the description has no response shapes (backend gap B4).\n */\n\n`;

const check = process.argv.includes('--check');
const live = process.argv.includes('--live');

async function fetchSpec(): Promise<string> {
  const base = process.env.BACKEND_URL ?? 'http://localhost:3000';
  const url = `${base.replace(/\/$/, '')}/api/docs-json`;
  const response = await fetch(url, { signal: AbortSignal.timeout(15000) });
  if (!response.ok) throw new Error(`${url} answered ${response.status}. Is the backend running with its API docs on?`);
  return `${JSON.stringify(await response.json(), null, 2)}\n`;
}

async function typesFrom(specText: string): Promise<string> {
  return HEADER + astToString(await openapiTS(JSON.parse(specText)));
}

const HTTP_METHODS = ['get', 'post', 'put', 'patch', 'delete'];
/** Our calls name paths under /api/v1 without that prefix (src/api/client.ts adds it). */
const API_PREFIX = '/api/v1';

function callsFrom(specText: string): string {
  const spec = JSON.parse(specText) as { paths: Record<string, Record<string, unknown>> };
  const calls = Object.entries(spec.paths)
    .filter(([path]) => path.startsWith(`${API_PREFIX}/`))
    .flatMap(([path, operations]) =>
      Object.keys(operations)
        .filter((method) => HTTP_METHODS.includes(method))
        .map((method) => `${method.toUpperCase()} ${path.slice(API_PREFIX.length)}`),
    )
    .sort();
  return `/**
 * GENERATED by npm run gen:types from the backend's OpenAPI description (src/types/generated/backend-openapi.json).
 * Do not edit by hand. Every backend call by its listed name: the only call names a server log may hold (Document 7,
 * section 20.10).
 */

export const BACKEND_CALLS = [
${calls.map((call) => `  '${call}',`).join('\n')}
] as const;

export type BackendCall = (typeof BACKEND_CALLS)[number];
`;
}

/** Writes the generated files from the stored description, without fetching it again. */
const offline = process.argv.includes('--from-stored');

async function main(): Promise<void> {
  if (offline) {
    const spec = await readFile(SPEC, 'utf8');
    await writeFile(TYPES, await typesFrom(spec));
    await writeFile(CALLS, callsFrom(spec));
    console.log(`Regenerated ${TYPES.slice(root.length)} and ${CALLS.slice(root.length)} from the stored description.`);
    return;
  }
  if (check && live) {
    const [fresh, stored] = await Promise.all([fetchSpec(), readFile(SPEC, 'utf8')]);
    if (fresh !== stored) {
      console.error('The backend OpenAPI description has changed since it was stored. Run npm run gen:types and review the difference.');
      process.exit(1);
    }
    console.log('The stored OpenAPI description matches the backend.');
    return;
  }
  if (check) {
    const [spec, stored, storedCalls] = await Promise.all([readFile(SPEC, 'utf8'), readFile(TYPES, 'utf8'), readFile(CALLS, 'utf8').catch(() => '')]);
    if ((await typesFrom(spec)) !== stored) {
      console.error('src/types/generated/backend-api.d.ts does not match the stored description. Run npm run gen:types; never edit it by hand.');
      process.exit(1);
    }
    if (callsFrom(spec) !== storedCalls) {
      console.error('src/types/generated/backend-calls.ts does not match the stored description. Run npm run gen:types; never edit it by hand.');
      process.exit(1);
    }
    console.log('Generated request types and backend-call names match the stored OpenAPI description.');
    return;
  }
  const spec = await fetchSpec();
  await writeFile(SPEC, spec);
  await writeFile(TYPES, await typesFrom(spec));
  await writeFile(CALLS, callsFrom(spec));
  console.log(`Stored the description and regenerated ${TYPES.slice(root.length)} and ${CALLS.slice(root.length)}. Review the difference before committing.`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
